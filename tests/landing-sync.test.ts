import { afterEach, expect, test } from "bun:test";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const temporaryDirectories: string[] = [];
const script = resolve(import.meta.dir, "../scripts/sync-landing-demo.ts");

function git(cwd: string, ...args: string[]) {
  const result = Bun.spawnSync(["git", ...args], {
    cwd,
    stdout: "pipe",
    stderr: "pipe",
  });
  if (result.exitCode !== 0) throw new Error(result.stderr.toString());
  return result.stdout.toString().trim();
}

afterEach(async () => {
  for (const directory of temporaryDirectories.splice(0)) {
    await rm(directory, { recursive: true, force: true });
  }
});

async function fixture() {
  const directory = await mkdtemp(join(tmpdir(), "guestin-sync-test-"));
  temporaryDirectories.push(directory);
  const remote = join(directory, "remote.git");
  const writer = join(directory, "writer");
  const landing = join(directory, "landing");
  const output = join(directory, "output");
  git(directory, "init", "--bare", remote);
  git(directory, "init", "--initial-branch=main", writer);
  git(writer, "config", "user.name", "Test");
  git(writer, "config", "user.email", "test@example.invalid");
  await writeFile(join(writer, "README.md"), "Application");
  git(writer, "add", ".");
  git(writer, "commit", "-m", "Initial application");
  const initial = git(writer, "rev-parse", "HEAD");
  git(writer, "remote", "add", "origin", remote);
  await writeFile(join(writer, "README.md"), "Passing application commit");
  git(writer, "commit", "-am", "Application update");
  const revision = git(writer, "rev-parse", "HEAD");
  git(writer, "push", "origin", "main");
  git(writer, "switch", "--create", "gh-pages", initial);
  await writeFile(
    join(writer, "demo-source.json"),
    JSON.stringify({ revision: initial }) + "\n",
  );
  await writeFile(join(writer, "README.md"), "Landing content");
  git(writer, "add", ".");
  git(writer, "commit", "-m", "Landing source");
  git(writer, "push", "origin", "gh-pages");
  git(directory, "clone", "--branch", "gh-pages", remote, landing);
  const run = (sha: string) =>
    Bun.spawnSync(["bun", script, sha], {
      cwd: landing,
      env: { ...process.env, GITHUB_OUTPUT: output },
      stdout: "pipe",
      stderr: "pipe",
    });
  return { directory, remote, writer, landing, output, initial, revision, run };
}

test("sync updates the pin and reruns deployment for an already synchronized commit", async () => {
  const state = await fixture();
  const result = state.run(state.revision);
  expect(result.stderr.toString()).not.toContain("error:");
  expect(result.exitCode).toBe(0);
  expect(
    JSON.parse(
      git(
        state.writer,
        "--git-dir",
        state.remote,
        "show",
        "gh-pages:demo-source.json",
      ),
    ).revision,
  ).toBe(state.revision);
  expect(
    git(state.writer, "--git-dir", state.remote, "show", "gh-pages:README.md"),
  ).toBe("Landing content");
  const synchronized = git(state.landing, "rev-parse", "HEAD");
  expect(state.run(state.revision).exitCode).toBe(0);
  expect(git(state.landing, "rev-parse", "HEAD")).toBe(synchronized);
  expect(await readFile(state.output, "utf8")).toBe(
    `revision=${state.revision}\nrevision=${state.revision}\n`,
  );
});

test("sync skips a superseded application commit", async () => {
  const state = await fixture();
  expect(state.run(state.initial).exitCode).toBe(0);
  expect(
    JSON.parse(await readFile(join(state.landing, "demo-source.json"), "utf8"))
      .revision,
  ).toBe(state.initial);
  expect(await readFile(state.output, "utf8")).toBe("revision=\n");
});

test("sync retries a rejected push and preserves the concurrent landing edit", async () => {
  const state = await fixture();
  const marker = join(state.directory, "raced");
  // The first push races with a normal website edit from another checkout.
  // Hook variables are filesystem paths generated by mkdtemp, passed as arguments.
  const hookScript = join(state.directory, "race.ts");
  await writeFile(
    hookScript,
    `import { existsSync, writeFileSync } from "node:fs";
const [marker, writer] = process.argv.slice(2);
if (!existsSync(marker)) {
  writeFileSync(marker, "raced");
  writeFileSync(writer + "/README.md", "Concurrent landing edit");
  for (const args of [["add", "README.md"], ["commit", "-m", "Concurrent edit"], ["push", "origin", "gh-pages"]]) {
    const result = Bun.spawnSync(["git", "-C", writer, ...args]);
    if (result.exitCode) throw Error(result.stderr.toString());
  }
}
`,
  );
  await writeFile(
    join(state.landing, ".git/hooks/pre-push"),
    `#!/bin/sh\nbun '${hookScript}' '${marker}' '${state.writer}'\n`,
    { mode: 0o755 },
  );
  const result = state.run(state.revision);
  expect(result.exitCode).toBe(0);
  expect(
    git(state.writer, "--git-dir", state.remote, "show", "gh-pages:README.md"),
  ).toBe("Concurrent landing edit");
  expect(
    JSON.parse(
      git(
        state.writer,
        "--git-dir",
        state.remote,
        "show",
        "gh-pages:demo-source.json",
      ),
    ).revision,
  ).toBe(state.revision);
});
